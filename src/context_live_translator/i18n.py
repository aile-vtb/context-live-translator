CATALOGS: Final = {"en": ENGLISH, "ja": JAPANESE}
SOURCE_TEXTS: Final = frozenset(ENGLISH) | frozenset(JAPANESE)
COMBO_KEY_ROLE: Final = int(Qt.ItemDataRole.UserRole) + 37


def normalize_ui_language(language: str) -> str:
    return language if language in SUPPORTED_UI_LANGUAGES else DEFAULT_UI_LANGUAGE


def set_ui_language(language: str) -> None:
    global _current_language
    _current_language = normalize_ui_language(language)


def current_ui_language() -> str:
    return _current_language


def tr(source: str, **values: object) -> str:
    translated = CATALOGS.get(_current_language, {}).get(source, source)
    return translated.format(**values) if values else translated


def _translate_property(
    widget: QWidget,
    property_name: str,
    current: str,
    setter: object,
) -> None:
    canonical = widget.property(property_name)
    if canonical is None and current in SOURCE_TEXTS:
        canonical = current
        widget.setProperty(property_name, canonical)
    if isinstance(canonical, str):
        setter(tr(canonical))


def localize_widget_tree(root: QWidget) -> None:
    widgets = [root, *root.findChildren(QWidget)]
    for widget in widgets:
        if widget.property("i18n_skip"):
            continue
        if isinstance(widget, QGroupBox):
            _translate_property(widget, "i18n_title", widget.title(), widget.setTitle)
        elif isinstance(widget, QAbstractButton):
            _translate_property(widget, "i18n_text", widget.text(), widget.setText)
        elif isinstance(widget, QLabel):
            _translate_property(widget, "i18n_text", widget.text(), widget.setText)
        if isinstance(widget, QLineEdit):
            _translate_property(
                widget,
                "i18n_placeholder",
                widget.placeholderText(),
                widget.setPlaceholderText,
            )
        if isinstance(widget, QComboBox):
            for index in range(widget.count()):
                canonical = widget.itemData(index, COMBO_KEY_ROLE)
                current = widget.itemText(index)
                if canonical is None and current in SOURCE_TEXTS:
                    canonical = current
                    widget.setItemData(index, canonical, COMBO_KEY_ROLE)
                if isinstance(canonical, str):
                    widget.setItemText(index, tr(canonical))
        if isinstance(widget, QTabWidget):
            canonical_tabs = widget.property("i18n_tabs")
            if not isinstance(canonical_tabs, list):
                canonical_tabs = [widget.tabText(index) for index in range(widget.count())]
                widget.setProperty("i18n_tabs", canonical_tabs)
            for index, canonical in enumerate(canonical_tabs[: widget.count()]):
                if canonical in SOURCE_TEXTS:
                    widget.setTabText(index, tr(canonical))
